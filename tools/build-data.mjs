#!/usr/bin/env node
// Writes data/data.js, the one file index.html loads. Run it after every edit of data/trip.json:
//   node tools/build-data.mjs
// The page never fetches: one module keeps the site quick on a slow hill network.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export async function bundle (root = ROOT) {
  return JSON.parse(await readFile(join(root, 'data', 'trip.json'), 'utf8'));
}

async function main () {
  const data = await bundle();
  const body = [
    '// Written by tools/build-data.mjs from data/trip.json. Do not edit this file by hand.',
    `export default ${JSON.stringify(data, null, 1)};`,
    ''
  ].join('\n');
  await writeFile(join(ROOT, 'data', 'data.js'), body);
  console.log(`data/data.js written (${Math.round(body.length / 1024)} KB): `
    + `${data.trips.length} versions of the trip, ${data.marks.length} Marks`);
}

if (process.argv[1] && process.argv[1].endsWith('build-data.mjs')) await main();
