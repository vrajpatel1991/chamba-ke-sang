#!/usr/bin/env node
// Writes data/data.js, the one file the pages load. Run it after every edit of data/*.json:
//   node tools/build-data.mjs
// The pages never fetch: one module keeps the site quick on a slow hill network.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['settings', 'partners', 'places', 'experiences', 'hosts', 'journeys', 'figures'];

export async function bundle (root = ROOT) {
  const out = {};
  for (const name of FILES) {
    out[name] = JSON.parse(await readFile(join(root, 'data', `${name}.json`), 'utf8'));
  }
  return out;
}

async function main () {
  const data = await bundle();
  const body = [
    '// Written by tools/build-data.mjs from data/*.json. Do not edit this file by hand:',
    '// edit the Sheet, export the CSV, run tools/sheet-to-json.mjs, then run tools/build-data.mjs.',
    `export default ${JSON.stringify(data, null, 1)};`,
    ''
  ].join('\n');
  await writeFile(join(ROOT, 'data', 'data.js'), body);
  const counts = FILES.map((n) => `${n} ${Array.isArray(data[n][n]) ? data[n][n].length : 1}`).join(', ');
  console.log(`data/data.js written (${Math.round(body.length / 1024)} KB): ${counts}`);
}

if (process.argv[1] && process.argv[1].endsWith('build-data.mjs')) await main();
